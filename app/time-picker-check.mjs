import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const browser=await chromium.launch({headless:true,channel:'msedge'});
try {
  const page=await browser.newPage({viewport:{width:1500,height:1100}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://localhost:5173');
  await page.locator('[aria-current="date"] .day-number').click();
  assert.equal(await page.locator('.timeline').evaluate(el=>Math.round(el.scrollTop)),await page.locator('[data-hour="12"]').evaluate(el=>Math.round(el.offsetTop)));
  await page.locator('[aria-current="date"] .add').click();
  await page.getByLabel('Start (valgfritt)',{exact:true}).click();
  assert.equal(await page.getByLabel('Start (valgfritt)',{exact:true}).evaluate(el=>el===document.activeElement),true);
  await page.keyboard.type('11:05');
  assert.equal(await page.getByLabel('Start (valgfritt)',{exact:true}).inputValue(),'11:05');
  await page.getByLabel('Start (valgfritt)',{exact:true}).fill('');
  await page.getByRole('button',{name:'Velg starttid',exact:true}).click();
  assert.equal(await page.getByLabel('Start (valgfritt): time',{exact:true}).inputValue(),'12');
  assert.equal(await page.getByLabel('Start (valgfritt): minutt',{exact:true}).inputValue(),'00');
  assert.deepEqual(await page.getByLabel('Start (valgfritt): minutt',{exact:true}).locator('option').allTextContents(),['00','05','10','15','20','25','30','35','40','45','50','55']);
  assert.equal(await page.getByLabel('Start (valgfritt)',{exact:true}).inputValue(),'');
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('.time-chooser').count(),0);
  assert.equal(await page.getByLabel('Start (valgfritt)',{exact:true}).inputValue(),'');
  await page.getByRole('button',{name:'Velg starttid',exact:true}).click();
  await page.getByLabel('Start (valgfritt): minutt',{exact:true}).selectOption('15');
  await page.getByRole('button',{name:'Bruk klokkeslett',exact:true}).click();
  assert.equal(await page.getByLabel('Start (valgfritt)',{exact:true}).inputValue(),'12:15');
  await page.getByRole('button',{name:'Velg sluttid',exact:true}).click();
  await page.getByLabel('Slutt (valgfritt): time',{exact:true}).selectOption('13');
  await page.getByLabel('Slutt (valgfritt): minutt',{exact:true}).selectOption('30');
  await page.getByRole('button',{name:'Bruk klokkeslett',exact:true}).click();
  await page.getByLabel('Hva skal du gjøre?').fill('Fem minutter');
  await page.getByLabel('Start (valgfritt)',{exact:true}).fill('12:13');
  await page.getByRole('button',{name:'Lagre oppgave',exact:true}).click();
  await page.getByRole('alert').filter({hasText:'femminutterssteg'}).waitFor();
  await page.getByLabel('Start (valgfritt)',{exact:true}).fill('12:15');
  await page.getByRole('button',{name:'Velg starttid',exact:true}).click();
  await page.screenshot({path:'app/test-results/time-picker.png',fullPage:true});
  await page.getByRole('button',{name:'Lukk',exact:true}).click();
  await page.getByRole('button',{name:'Lagre oppgave',exact:true}).click();
  await page.waitForSelector('#editor',{state:'detached'});
  await page.reload();
  await page.locator('.week').getByRole('button',{name:'Rediger Fem minutter',exact:true}).click();
  assert.equal(await page.getByLabel('Start (valgfritt)',{exact:true}).inputValue(),'12:15');
  await page.getByRole('button',{name:'Velg starttid',exact:true}).click();
  assert.equal(await page.getByLabel('Start (valgfritt): minutt',{exact:true}).inputValue(),'15');
  await page.getByRole('button',{name:'Fjern klokkeslett',exact:true}).click();
  await page.getByLabel('Slutt (valgfritt)',{exact:true}).fill('');
  await page.getByRole('button',{name:'Lagre oppgave',exact:true}).click();
  await page.waitForSelector('#editor',{state:'detached'});
  // Old minute-precise data must remain editable without an automatic rounding migration.
  await page.evaluate(()=>{const data=JSON.parse(localStorage.getItem('smart-todo.v1'));data.tasks[0].start='12:13';data.tasks[0].end='13:37';localStorage.setItem('smart-todo.v1',JSON.stringify(data));});
  await page.reload();
  await page.locator('.week').getByRole('button',{name:'Rediger Fem minutter',exact:true}).click();
  await page.getByLabel('Hva skal du gjøre?').fill('Eksisterende minutter');
  await page.getByRole('button',{name:'Lagre oppgave',exact:true}).click();
  await page.waitForSelector('#editor',{state:'detached'});
  assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('smart-todo.v1')).tasks[0].start),'12:13');
  assert.deepEqual(errors,[]);
  console.log('Picker checks passed: noon scroll and empty preview, five-minute menu, explicit apply, validation, persistence, clear times, legacy preservation.');
} finally {await browser.close();}
