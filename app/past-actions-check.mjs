import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const {chromium}=createRequire(import.meta.url)(process.env.PLAYWRIGHT_MODULE||'playwright');
const browser=await chromium.launch({headless:true,channel:'msedge'});
try {
  const context=await browser.newContext({viewport:{width:1440,height:1000},timezoneId:'Europe/Oslo'});
  const page=await context.newPage(),errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.clock.setFixedTime(new Date('2026-11-23T12:00:00+01:00'));
  await page.goto('http://localhost:5173');
  const tasks=['Rapport','Lesing','Handle'].map((title,i)=>({id:String(i),title,description:`Detaljer ${i}`,date:`2026-11-${20+i}`,category:'Jobb',start:'12:00',end:'13:00'}));
  await page.evaluate(tasks=>localStorage.setItem('smart-todo.v1',JSON.stringify({version:1,tasks})),tasks);
  await page.reload();await page.locator('#past-open').click();
  const dialog=page.locator('#past-dialog');
  const records=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('smart-todo.v1')).tasks);
  const failWrites=()=>page.evaluate(()=>{window.originalSet=Storage.prototype.setItem;Storage.prototype.setItem=()=>{throw new Error('quota');};});
  const restoreWrites=()=>page.evaluate(()=>{Storage.prototype.setItem=window.originalSet;});
  await failWrites();
  await dialog.getByRole('button',{name:'Lagre som utført: Rapport',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('#past-action-error').textContent.includes('ikke lagret'));
  assert.equal((await records())[0].completed,undefined);
  assert.equal(await page.locator('#past-list li').count(),3);
  assert.equal(await dialog.getByRole('button',{name:'Lagre som utført: Rapport',exact:true}).evaluate(el=>el===document.activeElement),true);
  await restoreWrites();
  await dialog.getByRole('button',{name:'Lagre som utført: Rapport',exact:true}).click();
  await page.waitForFunction(()=>document.querySelectorAll('#past-list li').length===2);
  assert.equal(await dialog.isVisible(),true);
  assert.equal((await records())[0].completed,true);
  assert.equal((await records())[0].description,'Detaljer 0');
  assert.equal(await page.locator('[data-date="2026-11-20"] .task.completed').count(),1);
  await dialog.getByRole('button',{name:'Endre: Lesing',exact:true}).click();
  assert.equal(await page.locator('#past-editor #editor').count(),1);
  await dialog.getByLabel('Dato',{exact:true}).fill('2026-11-01');
  await dialog.getByLabel('Hva skal du gjøre?',{exact:true}).fill('Lesing endret');
  await dialog.getByRole('button',{name:'Lagre oppgave',exact:true}).click();
  await page.waitForSelector('#past-editor #editor',{state:'detached'});
  assert.equal(await dialog.isVisible(),true);
  assert.equal(await page.locator('#past-list h3').first().innerText(),'Lesing endret');
  assert.equal((await records())[1].description,'Detaljer 1');
  await dialog.getByRole('button',{name:'Endre: Lesing endret',exact:true}).click();
  await dialog.getByLabel('Dato',{exact:true}).fill('2026-11-23');
  await dialog.getByRole('button',{name:'Lagre oppgave',exact:true}).click();
  await page.waitForSelector('#past-editor #editor',{state:'detached'});
  assert.equal(await page.locator('#past-list li').count(),1);
  await dialog.getByRole('button',{name:'Endre: Handle',exact:true}).click();
  await dialog.getByLabel('Hva skal du gjøre?',{exact:true}).fill('Ulagret handling');
  page.once('dialog',d=>d.dismiss());await page.locator('#past-close').click();
  assert.equal(await page.locator('#past-editor #editor').count(),1);
  await failWrites();
  await dialog.getByRole('button',{name:'Lagre oppgave',exact:true}).click();
  await page.locator('#past-editor [role=alert]').filter({hasText:'ikke lagret'}).waitFor();
  assert.equal(await dialog.getByLabel('Hva skal du gjøre?',{exact:true}).inputValue(),'Ulagret handling');
  await restoreWrites();
  // Resolving the last task in another tab must not close this active draft.
  const other=await context.newPage();await other.goto('http://localhost:5173');
  await other.evaluate(()=>{const state=JSON.parse(localStorage.getItem('smart-todo.v1'));state.tasks.find(t=>t.id==='2').completed=true;localStorage.setItem('smart-todo.v1',JSON.stringify(state));});
  await page.waitForFunction(()=>document.querySelector('#past-heading').textContent.includes('(0)'));
  assert.equal(await dialog.isVisible(),true);
  assert.equal(await dialog.getByLabel('Hva skal du gjøre?',{exact:true}).inputValue(),'Ulagret handling');
  await dialog.getByRole('button',{name:'Lagre oppgave',exact:true}).click();
  await page.locator('#past-editor [role=alert]').filter({hasText:'annen fane'}).waitFor();
  assert.equal((await records())[2].title,'Handle');
  page.once('dialog',d=>d.accept());await dialog.getByRole('button',{name:'Avbryt',exact:true}).click();
  assert.equal(await dialog.isVisible(),false);
  assert.equal(await page.locator('#past-notice').isVisible(),false);
  // Last-task completion closes the window and retains the record in Fullført.
  await other.evaluate(()=>{const state=JSON.parse(localStorage.getItem('smart-todo.v1'));state.tasks.find(t=>t.id==='2').completed=false;localStorage.setItem('smart-todo.v1',JSON.stringify(state));});
  await page.waitForSelector('#past-open',{state:'visible'});await page.locator('#past-open').click();
  await dialog.getByRole('button',{name:'Endre: Handle',exact:true}).focus();
  const previousButton=await dialog.getByRole('button',{name:'Endre: Handle',exact:true}).elementHandle();
  await other.evaluate(()=>{const state=JSON.parse(localStorage.getItem('smart-todo.v1'));state.tasks.find(t=>t.id==='2').description='Oppdatert detalj';localStorage.setItem('smart-todo.v1',JSON.stringify(state));});
  await page.waitForFunction(button=>!button.isConnected,previousButton);
  await page.waitForFunction(()=>document.querySelector('#past-list [data-action=edit]')===document.activeElement);
  await page.screenshot({path:'app/test-results/past-actions.png'});
  await dialog.getByRole('button',{name:'Lagre som utført: Handle',exact:true}).click();
  await page.waitForFunction(()=>!document.querySelector('#past-dialog').open);
  await page.locator('#completed-toggle').click();
  assert.match(await page.locator('#completed-panel').innerText(),/Handle/);
  assert.equal((await records()).length,3);
  await other.evaluate(()=>{const state=JSON.parse(localStorage.getItem('smart-todo.v1'));state.tasks.find(t=>t.id==='2').completed=false;localStorage.setItem('smart-todo.v1',JSON.stringify(state));});
  await page.waitForSelector('#past-open',{state:'visible'});await page.locator('#past-open').click();
  await dialog.getByRole('button',{name:'Endre: Handle',exact:true}).click();
  await dialog.getByLabel('Hva skal du gjøre?',{exact:true}).fill('Skal forkastes');
  page.once('dialog',d=>d.accept());await dialog.getByRole('button',{name:'Avbryt',exact:true}).click();
  assert.equal((await records())[2].title,'Handle');assert.equal(await dialog.isVisible(),true);
  await dialog.getByRole('button',{name:'Endre: Handle',exact:true}).click();
  await dialog.getByLabel('Dato',{exact:true}).fill('');
  await dialog.getByRole('button',{name:'Lagre oppgave',exact:true}).click();
  await page.locator('#past-editor [role=alert]').filter({hasText:'Velg en dato'}).waitFor();
  await dialog.getByLabel('Start (valgfritt)',{exact:true}).fill('');
  await dialog.getByLabel('Slutt (valgfritt)',{exact:true}).fill('');
  await page.screenshot({path:'app/test-results/past-editor.png'});
  await dialog.getByRole('button',{name:'Lagre oppgave',exact:true}).click();
  await page.waitForFunction(()=>!document.querySelector('#past-dialog').open);
  assert.equal((await records())[2].date,'');assert.equal((await records())[2].description,'Oppdatert detalj');
  assert.deepEqual(errors,[]);
  console.log('Past action checks passed: completion, reschedule within/outside past, form reuse, cancel/cross protection, failures, cross-tab stale drafts, final closure and retained completed tasks.');
} finally {await browser.close();}
